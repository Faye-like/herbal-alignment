def build_resolved_plan(concerns, conn=None):
    """多关注点治理合并。

    对用户选取的多个养生困扰，对运动 / 日常注意 / 补剂做智能合并：
    - 日常注意：拼成 **1 条整合性综合建议**，结合通用原则与所选困扰的关键要点；
    - 运动：通用基础 2 条 + 最多 2 条特有针对性动作，上限 4 条；
    - 补剂：按通用性取 TOP 2；
    - 食谱重点（foods）保持 per-concern 展示（不同困扰膳食重点存在合理差异）。
    """
    close_conn = False
    if conn is None:
        conn = get_conn()
        close_conn = True

    try:
        # ---------- 1. 运动合并 ----------
        merged_exercise = list(_UNIVERSAL_EXERCISE_BASE)
        specific = []
        seen_titles = {e['title'] for e in merged_exercise}
        for c in concerns:
            tpl = _CONCERN_SPECIFIC_EXERCISE.get(c)
            if tpl:
                title, detail = tpl
                if title not in seen_titles:
                    specific.append({'title': title, 'detail': detail})
                    seen_titles.add(title)
        merged_exercise.extend(specific[:2])
        merged_exercise = merged_exercise[:4]

        # ---------- 2. 日常注意：拼成 1 条整合性综合建议 ----------
        merged_care = _build_merged_care(concerns)

        # ---------- 3. 补剂合并 ----------
        # 策略：按「通用性」排序取 TOP 2，统一带「食补优先 + 遵医嘱」前置声明（在前端统一展示一次）
        supplements = []
        seen_supp = set()

        # 先查通用基础补剂
        rows = conn.execute(
            'SELECT * FROM supplement WHERE name IN ({seq}) ORDER BY sort_order'.format(
                seq=','.join(['?'] * len(_UNIVERSAL_SUPPLEMENT_NAMES))
            ),
            _UNIVERSAL_SUPPLEMENT_NAMES,
        ).fetchall()
        for r in rows:
            d = dict(r)
            if d['name'] in seen_supp:
                continue
            seen_supp.add(d['name'])
            d['concern'] = '通用基础'
            supplements.append(d)

        # 如有剩余名额，补充困扰特有的补剂（仅限该困扰独有的补剂，不是被通用池覆盖的）
        # 先统计每个补剂被多少个困扰引用
        ref_counts = {}
        ref_rows = conn.execute('SELECT supplement_id, COUNT(*) as cnt FROM supplement_ref GROUP BY supplement_id').fetchall()
        for rr in ref_rows:
            ref_counts[rr['supplement_id']] = rr['cnt']

        for c in concerns:
            if len(supplements) >= 2:  # 最终上限 2 条
                break
            sub = conn.execute(
                '''SELECT s.*, sr.note
                     FROM supplement_ref sr
                     JOIN supplement s ON s.id = sr.supplement_id
                    WHERE sr.concern = ?
                 ORDER BY sr.sort_order, s.sort_order''',
                (c,)).fetchall()
            for r in sub:
                d = dict(r)
                if d['name'] in seen_supp:
                    continue
                # 跳过被 ≥3 个困扰引用的（已经在通用池里了）
                if ref_counts.get(d['id'], 0) >= 3:
                    continue
                seen_supp.add(d['name'])
                d['concern'] = c
                supplements.append(d)
                break  # 每个困扰最多加 1 条特有补剂

        supplements = supplements[:2]  # 最终上限 2 条

        # ---------- 4. 食谱重点（foods）保持 per-concern 展示，不改合并 ----------
        # 但限制每个困扰最多 3 条，避免过长
        by_concern = []
        for c in concerns:
            plan = CONCERN_DAILY_PLAN.get(c)
            if not plan:
                continue
            foods = [{'title': t, 'detail': d} for t, d in plan['foods'][:3]]
            by_concern.append({
                'concern': c,
                'foods': foods,
                'source': plan['source'],
            })

        return {
            'week_menu': week_menu_for(concerns),
            'merged_exercise': merged_exercise,
            'merged_care': merged_care,
            'supplements': supplements,
            'supplement_disclaimer': _SUPPLEMENT_DISCLAIMER,
            'by_concern': by_concern,
            'sources': PLAN_SOURCES + ['国家卫健委《健康中国行动》', '国家体育总局科学健身指导'],
            'disclaimer': '以上建议依据权威指南整理，仅作健康生活方式参考，不构成医疗建议。如有不适请及时就医。',
        }
    finally:
        if close_conn:
            conn.close()


