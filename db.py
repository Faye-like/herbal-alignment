def week_menu_for(concerns):
    """按关注点生成一周食谱。

    - 无关注点：回退到通用均衡食谱 BASE_WEEK_MENU；
    - 单一关注点：直接返回该困扰的定制食谱；
    - 多个关注点：逐天逐餐合并各食谱（去重、保持顺序，每餐最多 6 项）。
    """
    menus = [CONCERN_WEEK_MENU[c] for c in concerns if c in CONCERN_WEEK_MENU]
    if not menus:
        return BASE_WEEK_MENU
    if len(menus) == 1:
        return menus[0]
    merged = []
    for i in range(7):
        row = {'day': menus[0][i]['day']}
        for meal in ('breakfast', 'lunch', 'dinner', 'snack'):
            items = []
            for m in menus:
                for part in m[i][meal].split(' + '):
                    part = part.strip()
                    if part and part not in items:
                        items.append(part)
            row[meal] = ' + '.join(items[:6])
        merged.append(row)
    return merged


