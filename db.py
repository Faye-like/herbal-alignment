def _build_merged_care(concerns):
    """把所选 concerns 的关键要点拼成 **1 条**整合性的日常注意建议。

    格式：
      通用原则；<困扰1要点>、<困扰2要点>；<就医提醒>。
    最多取 4 个困扰的要点（每困扰 1~2 个短语），
    保证整句不超过约 180 字，紧凑好读。
    """
    picked_ingredients = []
    seen = set()
    # 每个困扰取 1 个核心短语，优先从第 1 个短语里挑，足够了
    for c in concerns:
        segs = _CARE_INGREDIENTS.get(c)
        if not segs:
            continue
        main = segs[0]  # 取第一个最核心的
        if main not in seen:
            picked_ingredients.append(main)
            seen.add(main)
        if len(picked_ingredients) >= 4:
            break

    if not picked_ingredients:
        return [_CARE_COMMON['open'] + '。' + _CARE_COMMON['close']]

    # 拼成一条流畅的话
    middle = '；'.join(picked_ingredients)
    merged = _CARE_COMMON['open'] + '；' + middle + '。' + _CARE_COMMON['close']
    return [merged]


