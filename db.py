def init_db(force: bool = False) -> None:
    """建表并写入种子数据（库非空时跳过种子）。"""
    if force and os.path.exists(DB_PATH):
        os.remove(DB_PATH)
    conn = get_conn()
    conn.executescript(SCHEMA)
    cur = conn.execute('SELECT COUNT(*) AS c FROM resource')
    if cur.fetchone()['c'] == 0:
        _seed(conn)
    if conn.execute('SELECT COUNT(*) AS c FROM care_plan').fetchone()['c'] == 0:
        _seed_care(conn)
    # 补剂与关联表：按名称增量补种，旧库也能获得新增品类
    _seed_supplements(conn, only_missing=True)
    _seed_supplement_ref(conn)
    _ensure_manual_chapters(conn)
    conn.commit()
    conn.close()


def _ensure_manual_chapters(conn: sqlite3.Connection) -> None:
    """为已初始化的旧库补齐新增的手册章节（按标题判重，可重复执行）。"""
    for title, rtype, themes, cons, ptime, content in MANUAL_EXTRA_CHAPTERS:
        exists = conn.execute(
            'SELECT id FROM resource WHERE title=? AND type=?', (title, rtype)).fetchone()
        if exists:
            continue
        conn.execute(
            'INSERT INTO resource(title, cover, content, type, theme_tags, concerns, publish_time, views) '
            'VALUES (?,?,?,?,?,?,?,?)',
            (title, '', content, rtype, _j(themes), _j(cons), ptime, 0))


