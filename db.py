def _supp_id(conn: sqlite3.Connection, name: str) -> int:
    """按补剂名称查 id，供种子函数关联用。"""
    row = conn.execute('SELECT id FROM supplement WHERE name=?', (name,)).fetchone()
    return row['id'] if row else 0


