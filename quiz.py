def _idx(value):
    """把前端传来的选项下标转成 0-3 分，非法值按 0 处理。"""
    return value if isinstance(value, int) and 0 <= value <= 3 else 0


def assess_body(body_answers):
    """5 个躯体维度打分：经常/持续存在（≥2 分）视为命中。"""
    hits = []
    for q in BODY_QUESTIONS:
        score = _idx(body_answers.get(q['id']))
        if score >= 2:
            d = BODY_DIMENSIONS[q['dim']]
            hits.append({
                'id': q['dim'], 'name': d['name'], 'label': d['label'], 'score': score,
                'risk': d['risk'], 'food_dish': d['food_dish'], 'food_desc': d['food_desc'],
            })
    hits.sort(key=lambda x: -x['score'])
    labels = [h['label'] for h in hits]
    return {
        'hits': hits,
        'labels': labels,
        'top': hits[0] if hits else None,
        'summary': ' + '.join(labels) if labels else '整体平稳型',
    }


def assess_mind(mind_answers):
    """3 道思虑内耗题打分：0-2 平稳，3-5 轻度，6-9 高。"""
    score = sum(_idx(mind_answers.get(q['id'])) for q in MIND_QUESTIONS)
    if score >= 6:
        level = 'high'
    elif score >= 3:
        level = 'mild'
    else:
        level = 'stable'
    info = MIND_LEVELS[level]
    return {
        'score': score, 'max': len(MIND_QUESTIONS) * 3,
        'level': level, 'label': info['label'],
        'desc': info['desc'], 'advice': info['advice'],
    }


