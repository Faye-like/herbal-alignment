def assess_bmi(height_cm, weight_kg):
    try:
        h = float(height_cm)
        w = float(weight_kg)
    except (TypeError, ValueError):
        return None
    if not (120 <= h <= 230 and 30 <= w <= 250):
        return None
    bmi = round(w / ((h / 100) ** 2), 1)
    if bmi < 18.5:
        level, label = 'under', '偏瘦'
        advice = '优先增加优质蛋白与总能量摄入（鸡蛋、奶、豆制品、瘦肉），配合抗阻训练，而不是只靠补剂。若近期体重明显下降，建议先排查消化与内分泌问题。'
