def build_food_plan(mind, body, supplements, top_id, bmi=None, custom_dims=None):
    """按人格 + 思虑等级 + 躯体状态 + BMI 组合食疗方案，并与现有补剂错开。

    数量固定上限 4 道：人格食疗 1 道 + BMI 对应 1 道 + 思虑等级 2-3 道，
    不随答题项数膨胀。
    """
    plan = dict(MIND_FOOD[mind['level']])
    dishes = []
    herb_dish = HERB_FOOD.get(top_id)
    if herb_dish:
        dishes.append(dict(herb_dish))
    if bmi and bmi.get('dish'):
        dishes.append(dict(bmi['dish']))
    if custom_dims:
        extra = CUSTOM_DIM_FOOD.get(custom_dims[0])
        if extra and not any(d['name'] == extra['name'] for d in dishes):
            dishes.append(dict(extra))
    if mind['level'] == 'stable' and body['top']:
        dishes.append({'name': body['top']['food_dish'], 'desc': body['top']['food_desc']})
    dishes.extend(list(plan['dishes']))
    plan['dishes'] = dishes[:4]
    if bmi:
        plan['style'] = plan['style'] + ' · BMI ' + bmi['label']
    if supplements:
        plan['supplement_note'] = ('食疗与补剂建议错开约 2 小时；不需要停掉你正在服用的补剂，'
                                   '如正在服药或有慢性病，调整前请先咨询医生。')
    else:
        plan['supplement_note'] = '目前没有服用补剂，优先通过饮食获取营养，不建议自行叠加补剂。'
    return plan


def _q15_texts(answers):
    """取行为问卷最后一题（多选 + 其他）的文本，兼容旧版单选下标。"""
    q15 = next((q for q in QUESTIONS if q.get('id') == 'q15'), None)
    if not q15:
        return [], ''
    val = answers.get('q15')
    picks, other = [], ''
    if isinstance(val, dict):
        for i in val.get('picks') or []:
            if isinstance(i, int) and 0 <= i < len(q15['options']):
                picks.append(q15['options'][i]['text'])
        other = str(val.get('other') or '').strip()
    elif isinstance(val, int) and 0 <= val < len(q15['options']):
        picks.append(q15['options'][val]['text'])
    return picks, other


