def supplement_advice(names):
    """整理正在服用的补剂与服用提醒。自定义补剂按关键词给出提示。"""
    out = []
    for name in (names or []):
        if not name or name == '目前没有服用':
            continue
        name = str(name).strip()
        if name.startswith('其他：'):
            label = name[3:].strip()
            if not label:
                continue
            note = next((n for k, n in CUSTOM_SUPPLEMENT_HINTS if k in label), '')
            out.append({'name': label,
                        'note': note or '未收录在该补剂库中，建议对照产品标签核对成分与剂量，避免与同类补剂叠加；如正在服药或有慢性病，先咨询医生。'})
