def parse_custom_texts(texts):
    """把用户自由填写 / 补充勾选的内容按关键词归类。

    返回 {'hits': [{text, dim, label, tip}], 'herbs': {药材塑: 加权分}, 'tips': [提示]}
    同一维度只保留第一次命中的说明，避免重复堆砌。
    """
    hits = []
    herbs = {}
    seen = set()
    for raw in texts:
        text = str(raw or '').strip()
        if not text:
            continue
        low = text.lower()
        for item in CUSTOM_KEYWORDS:
            if item['dim'] in seen:
                continue
            if not any(w.lower() in low for w in item['words']):
                continue
            seen.add(item['dim'])
            hits.append({'text': text, 'dim': item['dim'], 'label': item['label'],
                         'tip': item['tip'], 'herbs': dict(item['herbs'])})
            for hid, pts in item['herbs'].items():
                if pts > 0:
                    herbs[hid] = herbs.get(hid, 0) + pts
            break
    return {'hits': hits, 'herbs': herbs, 'tips': [h['tip'] for h in hits]}

