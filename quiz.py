def calculate_match(answers, body=None, mind=None, custom_hits=None):
    """行为问卷 + 躯体维度 + 思虑倾向综合打分，返回排序、首选与匹配依据。

    answers: dict {question_id: option_index}
    body:    assess_body() 的结果（可为 None）
    mind:    assess_mind() 的结果（可为 None）
    custom_hits: parse_custom_texts() 的关键词命中项，用于小幅加权
    """
    scores = {hid: 0 for hid in HERB_TYPES}
    expected = {hid: 0.0 for hid in HERB_TYPES}   # 该药材塑在已答题目里的平均可得分的累计
    evidence = {hid: [] for hid in HERB_TYPES}

    def add(hid, pts, dim, answer):
        if pts <= 0 or hid not in scores:
            return
        scores[hid] += pts
        evidence[hid].append({'dim': dim, 'answer': answer, 'points': pts})

    for q in QUESTIONS:
        if q.get('skip_match'):
            continue
        idx = answers.get(q['id'])
        if idx is None or idx < 0 or idx >= len(q['options']):
            continue
        opt = q['options'][idx]
        for hid, pts in opt['scores'].items():
            add(hid, pts, q.get('dim', '行为偏好'), opt['text'])
        # 期望分：该题四个选项给这味药材塑的平均分，用来校正「出现题目多就更容易累计高分」
        for hid in HERB_TYPES:
            best = max(o['scores'].get(hid, 0) for o in q['options'])
            expected[hid] += best / len(q['options'])

    for h in ((body or {}).get('hits') or []):
        bonus = BODY_HERB_BONUS.get(h['id'], {})
        primary = max(bonus, key=bonus.get) if bonus else None
        for hid, pts in bonus.items():
            extra = pts + (1 if h['score'] >= 3 and hid == primary else 0)
            add(hid, extra, '躯体状态', h['name'] + '（' + h['label'] + '）')

    level = (mind or {}).get('level')
    for hid, pts in MIND_HERB_BONUS.get(level, {}).items():
        add(hid, pts, '思虑状态', (mind or {}).get('label', ''))

    for hit in (custom_hits or []):
        for hid, pts in (hit.get('herbs') or {}).items():
            add(hid, pts, '自定义补充', hit.get('text', ''))

    # 匹配指数 = 实得分 / √期望分：既保留累计证据，又避免「题目覆盖多」的药材塑天然占优
    index = {hid: (scores[hid] / math.sqrt(expected[hid]) if expected[hid] else 0.0)
             for hid in HERB_TYPES}
    total_idx = sum(index.values()) or 1

    ranked = sorted(
        HERB_TYPES,
        key=lambda h: (-index[h], -scores[h], h),
    )
    scores_list = []
    for hid in ranked:
        scores_list.append({
            'id': hid,
            'name': HERB_TYPES[hid]['name'],
            'herb': HERB_TYPES[hid]['herb'],
            'image': HERB_TYPES[hid]['image'],
            'color': HERB_TYPES[hid]['color'],
            'score': scores[hid],
            'percent': round(index[hid] / total_idx * 100, 1),
        })
    top_id = ranked[0] if ranked else 'lavender'
    basis = sorted(evidence[top_id], key=lambda e: -e['points'])[:3]
    return top_id, scores_list, basis


def build_report(answers, body=None, mind=None, custom_hits=None):
    """生成完整报告数据。"""
    top_id, scores_list, basis = calculate_match(answers, body, mind, custom_hits)

    top = dict(HERB_TYPES[top_id])
    top['id'] = top_id

    second = None
    if len(scores_list) > 1:
        sid = scores_list[1]['id']
        second = dict(HERB_TYPES[sid])
        second['id'] = sid
        second['percent'] = scores_list[1]['percent']

    all_types = []
    for hid, info in HERB_TYPES.items():
        item = dict(info)
        item['id'] = hid
        all_types.append(item)

    return {
        'top_id': top_id,
        'herb': top,
        'second': second,
        'scores': scores_list,
        'basis': basis,
        'match_reason': HERB_MATCH_REASON.get(top_id, ''),
        'all_types': all_types,
        'total_types': len(all_types),
        'questions_count': len(QUESTIONS),
    }


